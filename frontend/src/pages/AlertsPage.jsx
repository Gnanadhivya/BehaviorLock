import React, { useState, useEffect } from 'react';
import Sidebar from '../components/dashboard/Sidebar';
import TopNavbar from '../components/dashboard/TopNavbar';
import api from '../services/api';
import { AlertTriangle, ShieldCheck, CheckCircle2, Filter, Loader2 } from 'lucide-react';

export default function AlertsPage() {
  const [alerts, setAlerts] = useState([]);
  const [filter, setFilter] = useState('ALL'); // ALL, UNREAD, HIGH_RISK, RESOLVED
  const [loading, setLoading] = useState(true);

  const fetchAlerts = async () => {
    try {
      const res = await api.get('/api/alerts');
      setAlerts(res.data || []);
    } catch (err) {
      console.error("Error loading alerts:", err);
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => {
    fetchAlerts();
  }, []);

  const handleResolveAlert = async (id) => {
    try {
      await api.post(`/api/alerts/${id}/resolve`);
      setAlerts(alerts.map(a => a.id === id ? { ...a, status: 'RESOLVED' } : a));
    } catch (err) {
      console.error("Error resolving alert:", err);
    }
  };

  const filteredAlerts = alerts.filter(alert => {
    if (filter === 'UNREAD') return alert.status === 'OPEN';
    if (filter === 'RESOLVED') return alert.status === 'RESOLVED';
    if (filter === 'HIGH_RISK') return alert.riskScore >= 60 || alert.severity === 'HIGH' || alert.severity === 'CRITICAL';
    return true;
  });

  const getSeverityStyle = (severity) => {
    switch (severity?.toUpperCase()) {
      case 'CRITICAL':
        return { bg: 'rgba(244,63,94,0.15)', border: 'rgba(244,63,94,0.4)', text: 'var(--accent-rose)' };
      case 'HIGH':
        return { bg: 'rgba(245,158,11,0.15)', border: 'rgba(245,158,11,0.4)', text: '#f59e0b' };
      case 'MEDIUM':
        return { bg: 'rgba(0,229,255,0.15)', border: 'rgba(0,229,255,0.4)', text: 'var(--accent-cyan)' };
      default:
        return { bg: 'rgba(16,185,129,0.15)', border: 'rgba(16,185,129,0.4)', text: 'var(--accent-emerald)' };
    }
  };

  return (
    <div style={{ display: 'flex', minHeight: '100vh', background: 'var(--bg-dark)' }}>
      <Sidebar />

      <div style={{ flex: 1, display: 'flex', flexDirection: 'column', minWidth: 0 }}>
        <TopNavbar title="Security Alerts & Incident Center" alertCount={alerts.filter(a => a.status === 'OPEN').length} />

        <div style={{ padding: '28px 32px', flex: 1, display: 'flex', flexDirection: 'column', gap: 24 }}>
          {/* Top Control Bar & Filters */}
          <div className="glass-card" style={{ padding: 20, display: 'flex', justifyContent: 'space-between', alignItems: 'center', flexWrap: 'wrap', gap: 16 }}>
            <div>
              <h2 style={{ fontSize: '1.2rem', fontWeight: 800 }}>Incident Security Alerts</h2>
              <p style={{ fontSize: '0.82rem', color: 'var(--text-secondary)', marginTop: 2 }}>
                Real-time security alert events generated by authoritative backend state engine
              </p>
            </div>

            {/* Filter Buttons */}
            <div style={{ display: 'flex', gap: 8, alignItems: 'center' }}>
              <Filter size={16} color="var(--text-muted)" style={{ marginRight: 4 }} />
              {['ALL', 'UNREAD', 'HIGH_RISK', 'RESOLVED'].map((f) => (
                <button
                  key={f}
                  onClick={() => setFilter(f)}
                  style={{
                    padding: '6px 14px',
                    borderRadius: 6,
                    fontSize: '0.78rem',
                    fontWeight: 700,
                    border: '1px solid var(--border-color)',
                    background: filter === f ? 'var(--accent-cyan)' : 'rgba(255,255,255,0.04)',
                    color: filter === f ? '#0a0d14' : 'var(--text-secondary)',
                    cursor: 'pointer'
                  }}
                >
                  {f.replace('_', ' ')}
                </button>
              ))}
            </div>
          </div>

          {/* Alert List */}
          {loading ? (
            <div className="glass-card" style={{ padding: 40, textAlign: 'center', color: 'var(--accent-cyan)' }}>
              <Loader2 size={32} style={{ animation: 'spin 1s linear infinite', margin: '0 auto 12px auto' }} />
              <p style={{ fontSize: '0.88rem' }}>Loading security alerts...</p>
            </div>
          ) : filteredAlerts.length > 0 ? (
            <div style={{ display: 'flex', flexDirection: 'column', gap: 16 }}>
              {filteredAlerts.map((alert) => {
                const sev = getSeverityStyle(alert.severity);
                return (
                  <div
                    key={alert.id}
                    className="glass-card"
                    style={{
                      padding: 22,
                      display: 'flex',
                      justify: 'space-between',
                      alignItems: 'center',
                      borderLeft: `4px solid ${alert.status === 'OPEN' ? sev.text : 'var(--accent-emerald)'}`
                    }}
                  >
                    <div style={{ display: 'flex', gap: 16, alignItems: 'flex-start' }}>
                      <div style={{ background: alert.status === 'OPEN' ? sev.bg : 'rgba(16,185,129,0.1)', padding: 12, borderRadius: 12, color: alert.status === 'OPEN' ? sev.text : 'var(--accent-emerald)' }}>
                        {alert.status === 'OPEN' ? <AlertTriangle size={22} /> : <ShieldCheck size={22} />}
                      </div>

                      <div>
                        <div style={{ display: 'flex', alignItems: 'center', gap: 10 }}>
                          <h3 style={{ fontSize: '1.02rem', fontWeight: 800, color: '#fff' }}>
                            {alert.alertType || alert.type || 'BEHAVIORAL_ANOMALY'}
                          </h3>
                          <span style={{
                            padding: '2px 8px',
                            borderRadius: 4,
                            fontSize: '0.72rem',
                            fontWeight: 800,
                            background: sev.bg,
                            border: `1px solid ${sev.border}`,
                            color: sev.text
                          }}>
                            SEVERITY: {alert.severity || 'LOW'}
                          </span>
                          <span style={{ fontSize: '0.78rem', background: 'rgba(255,255,255,0.05)', padding: '2px 8px', borderRadius: 4, fontFamily: 'var(--font-mono)', fontWeight: 700, color: 'var(--text-secondary)' }}>
                            Risk Score: {alert.riskScore}/100
                          </span>
                        </div>

                        <p style={{ fontSize: '0.85rem', color: 'var(--text-secondary)', marginTop: 6, lineHeight: 1.4 }}>
                          {alert.reason || alert.message || 'Behavioral anomaly detected'}
                        </p>

                        <div style={{ fontSize: '0.76rem', color: 'var(--text-muted)', marginTop: 8, fontFamily: 'var(--font-mono)' }}>
                          Triggered at: {alert.createdAt || alert.timestamp}
                        </div>
                      </div>
                    </div>

                    <div style={{ display: 'flex', alignItems: 'center', gap: 12 }}>
                      {alert.status === 'OPEN' ? (
                        <button
                          onClick={() => handleResolveAlert(alert.id)}
                          style={{
                            padding: '8px 16px',
                            borderRadius: 8,
                            background: 'rgba(16,185,129,0.15)',
                            border: '1px solid rgba(16,185,129,0.4)',
                            color: 'var(--accent-emerald)',
                            fontWeight: 700,
                            fontSize: '0.82rem',
                            cursor: 'pointer',
                            display: 'flex',
                            alignItems: 'center',
                            gap: 6
                          }}
                        >
                          <CheckCircle2 size={14} /> Resolve Alert
                        </button>
                      ) : (
                        <span className="status-badge verified" style={{ fontSize: '0.72rem' }}>
                          RESOLVED
                        </span>
                      )}
                    </div>
                  </div>
                );
              })}
            </div>
          ) : (
            <div className="glass-card" style={{ padding: 36, textAlign: 'center', color: 'var(--text-muted)' }}>
              <ShieldCheck size={36} color="var(--accent-emerald)" style={{ margin: '0 auto 12px auto' }} />
              <h3 style={{ fontSize: '1.05rem', fontWeight: 700, color: '#fff' }}>Zero Unresolved Alerts</h3>
              <p style={{ fontSize: '0.83rem', marginTop: 4 }}>No security alerts match the selected filter criteria.</p>
            </div>
          )}
        </div>
      </div>
    </div>
  );
}
